#!/usr/bin/env python3
"""Export installed dependency notices; fail if a license has no source text."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "ui/public/third-party-notices.txt"


def json_command(*args):
    return json.loads(subprocess.check_output(args, cwd=ROOT, text=True))


def license_files(directory):
    return sorted(p for p in directory.iterdir() if p.is_file() and
                  p.name.lower().startswith(("license", "licence", "copying", "notice",
                                             "copyright", "authors")))


def render():
    sources = json.loads((ROOT / "licenses/upstream.json").read_text())
    packages = {}
    metadata = json_command("cargo", "metadata", "--locked", "--format-version", "1")
    for package in metadata["packages"]:
        if package["name"] == "command-scheduler":
            continue
        key = f"rust:{package['name']}@{package['version']}"
        packages[key] = (package["license"], Path(package["manifest_path"]).parent,
                         package.get("repository"), package.get("authors", []))
    javascript = json_command("pnpm", "licenses", "list", "--prod", "--json")
    for entries in javascript.values():
        for entry in entries:
            for path in entry["paths"]:
                directory = Path(path)
                package = json.loads((directory / "package.json").read_text())
                key = f"npm:{package['name']}@{package['version']}"
                packages[key] = (entry["license"], directory,
                                 package.get("homepage"), [])
    sections = [
        "COMMAND SCHEDULER — THIRD-PARTY NOTICES\n\n"
        "Generated by scripts/export_third_party_notices.py from locked dependencies.\n"
        "Includes Rust dependencies for all platforms and npm production dependencies.\n"
        "These components retain their own licenses; the project's MIT license does not replace them.\n"
        "For alternative license expressions, preserve the upstream texts supplied here.\n"
    ]
    for key, (license_id, directory, repository, authors) in sorted(packages.items()):
        if not license_id:
            raise RuntimeError(f"Missing license identifier: {key}")
        header = f"\n{'=' * 72}\n{key}\nLicense: {license_id}\n"
        if repository:
            header += f"Upstream: {repository}\n"
        if authors:
            header += "Authors (package metadata): " + "; ".join(authors) + "\n"
        files = license_files(directory)
        texts = [f"\n--- {p.name} ---\n{p.read_text(encoding='utf-8')}" for p in files]
        if key in sources:
            item = sources[key]
            header += f"Additional license source: {item['source']}\n"
            source = ROOT / item["path"]
            if hashlib.sha256(source.read_bytes()).hexdigest() != item["sha256"]:
                raise RuntimeError(f"Cached upstream license checksum mismatch: {key}")
            texts.append(source.read_text(encoding="utf-8"))
        if not texts:
            raise RuntimeError(f"No license/notice text available: {key}")
        sections.append(header + "\n".join(texts).rstrip() + "\n")
    return "\n".join(sections), len(packages)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, count = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("Third-party notices are stale; run scripts/export_third_party_notices.py")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print(f"Third-party notices: {count} dependency versions; {'verified' if args.check else 'exported'}")


if __name__ == "__main__":
    main()
